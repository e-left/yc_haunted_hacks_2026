#!/usr/bin/env bash
# Shared helpers for phase scripts. Source it; don't run it.
# Bash 3.2 compatible (the macOS default).

set -euo pipefail

PHASES_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$PHASES_DIR/.." && pwd)"
BACKEND="$ROOT/backend"
ENV_FILE="$BACKEND/.env"
FAILURES=0

pass() { printf '  \033[32mPASS\033[0m %s\n' "$1"; }
fail() { printf '  \033[31mFAIL\033[0m %s\n' "$1"; FAILURES=$((FAILURES + 1)); }
step() { printf '\n\033[1m== %s\033[0m\n' "$1"; }

# expect <description> <expected> <actual>
expect() {
  if [ "$2" = "$3" ]; then pass "$1"; else fail "$1 (expected '$2', got '$3')"; fi
}

ensure_built() { (cd "$BACKEND" && cargo build -q --bins); }

# gen_key <client_id>  ->  prints "<plaintext> <hash>"
gen_key() { "$BACKEND/target/debug/keygen" "$1" --raw; }

# Fresh demo-customer + other-agent keys, exported for the server and the smoke test.
fresh_demo_keys() {
  local customer_hash other_hash
  read -r CUSTOMER_KEY customer_hash <<<"$(gen_key demo-customer)"
  read -r OTHER_KEY other_hash <<<"$(gen_key other-agent)"
  LILD_API_KEYS="demo-customer:$customer_hash,other-agent:$other_hash"
  export CUSTOMER_KEY OTHER_KEY LILD_API_KEYS
}

# Local Postgres from compose.yaml (dev password, bound to 127.0.0.1 only).
LOCAL_DATABASE_URL="postgres://lild:lild_dev_password@127.0.0.1:54329/lild"
LOCAL_TEST_DATABASE_URL="postgres://lild:lild_dev_password@127.0.0.1:54329/lild_test"

ensure_postgres() {
  if ! docker info >/dev/null 2>&1; then
    echo "Docker is not running. Start Docker Desktop and retry." >&2
    return 1
  fi
  (cd "$ROOT" && docker compose up -d --wait postgres >/dev/null 2>&1) || {
    echo "Postgres failed to start: run 'docker compose up postgres' to see why." >&2
    return 1
  }
}

# Make sure backend/.env has demo keys; create them on first run. Loads the file.
ensure_env_keys() {
  load_env
  if [ -z "${LILD_API_KEYS:-}" ]; then
    fresh_demo_keys
    (
      umask 077
      cat >>"$ENV_FILE" <<EOF
# Demo keys (generated by phases scripts). Never commit this file.
LILD_API_KEYS=$LILD_API_KEYS
CUSTOMER_KEY=$CUSTOMER_KEY
OTHER_KEY=$OTHER_KEY
EOF
    )
    echo "Added fresh demo keys to $ENV_FILE"
  fi
}

# ensure_agent_key <client_id> <VAR>: give an agent (claude-agent, codex-agent, ...) its own
# key. If <VAR> isn't in backend/.env yet, generate a key, store the plaintext as VAR=..., and
# add client_id:hash to LILD_API_KEYS so the server accepts it after a restart.
# Sets NEW_AGENT_KEY=1 when a key was created.
ensure_agent_key() {
  local client="$1" var="$2" key hash tmp
  NEW_AGENT_KEY=0
  # Decide by the file, not by variables that may already be exported in this shell.
  if [ ! -f "$ENV_FILE" ]; then
    (unset LILD_API_KEYS CUSTOMER_KEY OTHER_KEY; ensure_env_keys) >/dev/null
  fi
  if grep -q "^$var=lild_live_" "$ENV_FILE"; then return 0; fi
  read -r key hash <<<"$(gen_key "$client")"
  tmp="$(mktemp)"
  awk -v add="$client:$hash" '
    /^LILD_API_KEYS=/ { print ($0 ~ /=$/ ? $0 add : $0 "," add); done = 1; next }
    { print }
    END { if (!done) print "LILD_API_KEYS=" add }' "$ENV_FILE" >"$tmp"
  printf '%s=%s\n' "$var" "$key" >>"$tmp"
  mv "$tmp" "$ENV_FILE"
  chmod 600 "$ENV_FILE"
  NEW_AGENT_KEY=1
}

# Load backend/.env if it exists (never committed).
load_env() {
  if [ -f "$ENV_FILE" ]; then
    set -a
    # shellcheck disable=SC1090
    . "$ENV_FILE"
    set +a
  fi
}

# start_server [port]: run the server binary in the background, wait for /v1/health.
start_server() {
  local port="${1:-$((18000 + RANDOM % 2000))}"
  BASE_URL="http://127.0.0.1:$port"
  SERVER_LOG="$(mktemp)"
  # Gates always use the stub pipeline so their checks stay deterministic.
  LILD_BIND="127.0.0.1:$port" LILD_PIPELINE=stub RUST_LOG=info "$BACKEND/target/debug/lild-backend" >"$SERVER_LOG" 2>&1 &
  SERVER_PID=$!
  trap stop_server EXIT
  export BASE_URL
  local i
  for i in $(seq 1 50); do
    if curl -sf "$BASE_URL/v1/health" >/dev/null 2>&1; then return 0; fi
    kill -0 "$SERVER_PID" 2>/dev/null || break
    sleep 0.2
  done
  echo "server failed to start; log:" >&2
  cat "$SERVER_LOG" >&2
  return 1
}

stop_server() {
  if [ -n "${SERVER_PID:-}" ]; then
    kill "$SERVER_PID" 2>/dev/null || true
    wait "$SERVER_PID" 2>/dev/null || true
    SERVER_PID=""
  fi
}

# http METHOD PATH [KEY] [IDEMPOTENCY_KEY] [BODY]
# Sets HTTP_STATUS, HTTP_HEADERS, HTTP_BODY.
http() {
  local method="$1" path="$2" key="${3:-}" idem="${4:-}" body="${5:-}"
  local hdr out
  hdr="$(mktemp)"; out="$(mktemp)"
  local args=(-s -X "$method" -D "$hdr" -o "$out" -w '%{http_code}' -H 'content-type: application/json')
  if [ -n "$key" ]; then args+=(-H "Authorization: Bearer $key"); fi
  if [ -n "$idem" ]; then args+=(-H "Idempotency-Key: $idem"); fi
  if [ -n "$body" ]; then args+=(--data "$body"); fi
  HTTP_STATUS="$(curl "${args[@]}" "$BASE_URL$path" || echo 000)"
  HTTP_HEADERS="$(cat "$hdr")"
  HTTP_BODY="$(cat "$out")"
  rm -f "$hdr" "$out"
}

# json_str <json> <field>: first string value of "field" (good enough for flat checks)
json_str() { printf '%s' "$1" | sed -n 's/.*"'"$2"'":"\([^"]*\)".*/\1/p' | head -1; }

# header_value <name>: value of a response header from the last http call (case-insensitive)
header_value() {
  printf '%s\n' "$HTTP_HEADERS" | tr -d '\r' | grep -i "^$1:" | head -1 | sed 's/^[^:]*:[[:space:]]*//'
}

finish() {
  if [ "$FAILURES" -eq 0 ]; then
    printf '\n\033[32mAll checks passed.\033[0m\n'
  else
    printf '\n\033[31m%d check(s) failed.\033[0m\n' "$FAILURES"
    exit 1
  fi
}
